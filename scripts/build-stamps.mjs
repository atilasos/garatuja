// Usage: node scripts/build-stamps.mjs /path/to/googlefonts/noto-emoji
import { copyFileSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { argv } from 'node:process';
import { URL } from 'node:url';

const [source] = argv.slice(2);
if (!source) throw new Error('Pass the path to a Noto Emoji checkout.');
const categories = [];
let category;
const files = new Set();
for (const line of readFileSync(new URL('./stamps.tsv', import.meta.url), 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  if (line.startsWith('@')) {
    const [pt, en] = line.slice(1).split('|');
    if (!pt || !en) throw new Error(line);
    category = { pt, en, entries: [] };
    categories.push(category);
    continue;
  }
  const [code, pt, en] = line.split('|');
  if (!category || !/^[\da-f]+(?:_[\da-f]+)*$/.test(code) || !pt || !en || files.has(code)) throw new Error(line);
  files.add(code);
  category.entries.push([code, pt, en]);
}

const vendor = new URL('../src/stamps/noto/', import.meta.url);
mkdirSync(vendor, { recursive: true });
for (const code of files) copyFileSync(resolve(source, 'svg', `emoji_u${code}.svg`), new URL(`emoji_u${code}.svg`, vendor));
copyFileSync(resolve(source, 'svg', 'LICENSE'), new URL('LICENSE', vendor));
const commit = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
writeFileSync(new URL('NOTICE', vendor), `Unmodified Noto Emoji SVGs by the Noto Emoji Project Authors.
Source: https://github.com/googlefonts/noto-emoji/tree/${commit}/svg
License: Apache License, Version 2.0 (see LICENSE).
`);
const manifest = categories.map(({ pt, en, entries }) =>
  `  [{ pt: ${JSON.stringify(pt)}, en: ${JSON.stringify(en)} }, [\n${entries.map(entry => '    ' + JSON.stringify(entry) + ',').join('\n')}\n  ]],`).join('\n');
writeFileSync(new URL('../src/stamps/noto/catalog.ts', import.meta.url),
  `// Generated by scripts/build-stamps.mjs from scripts/stamps.tsv.\nexport const catalog = [\n${manifest}\n] as const;\n`);

for (const file of readdirSync(vendor)) {
  const code = /^emoji_u([\da-f_]+)\.svg$/.exec(file)?.[1];
  if (code && !files.has(code)) unlinkSync(new URL(file, vendor));
}
